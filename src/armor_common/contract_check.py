"""armor-contract-check: validate messages and vector files against the published contracts, without any ../ path to the ARMOR-COMMON checkout.

  armor-contract-check message TOPIC [FILE]      validate one JSON message (FILE or standard input) for a topic
  armor-contract-check vectors PATH [PATH ...]   run vector files ({"kind": ..., "vectors": [{"name", "valid", "payload"}]}) against the schemas
  armor-contract-check matrix [--markdown] [--consumers]  the contracts and what the shared vectors say about each; with --check FILE, fail when FILE is out of date
  armor-contract-check kinds                     the message kinds that have a published schema

Exit status: 0 everything accepted or rejected as stated, 1 a mismatch, 2 a usage error.

Copyright (C) 2026 JuanenRac (Electro Hobby 3D). GPL-3.0-or-later.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

from .contracts import ContractError, validate_message, validate_payload

SCHEMAS = Path(__file__).resolve().parent / "schemas"


def kinds() -> list[str]:
    """The kinds that have a published schema (the file names of the schemas folder)."""
    return sorted(path.name[: -len(".schema.json")] for path in SCHEMAS.glob("*.schema.json"))


def check_vector_file(path: Path) -> tuple[int, list[str]]:
    """Run one vector file: the number of vectors checked and the list of mismatches."""
    try:
        document = json.loads(path.read_text(encoding="utf-8"))
        kind = document["kind"]
        vectors = document["vectors"]
    except (OSError, ValueError, KeyError, TypeError) as error:
        return 0, [f"{path}: not a vector file ({error})"]
    problems: list[str] = []
    for index, vector in enumerate(vectors):
        name = vector.get("name", f"#{index}") if isinstance(vector, dict) else f"#{index}"
        try:
            payload = vector["payload"]
            expected = bool(vector["valid"])
        except (KeyError, TypeError):
            problems.append(f"{path}: vector {name!r} needs 'valid' and 'payload'")
            continue
        try:
            validate_payload(kind, payload)
            accepted = True
        except ContractError as error:
            accepted = False
            reason = str(error)
        if accepted and not expected and not vector.get("schema_valid"):
            problems.append(f"{path}: {name!r} is accepted but must be refused")
        elif not accepted and expected:
            problems.append(f"{path}: {name!r} is refused ({reason}) but must be accepted")
    return len(vectors), problems


def collect_vector_files(paths: list[str]) -> list[Path]:
    files: list[Path] = []
    for item in paths:
        path = Path(item)
        files.extend(sorted(path.glob("*.json")) if path.is_dir() else [path])
    return files


def matrix_rows(conformance: Path | None = None) -> list[dict[str, Any]]:
    """One row per kind with a schema: the number of accepted and refused vectors of the shared conformance folder (when it is there)."""
    counts: dict[str, tuple[int, int]] = {}
    if conformance is not None and conformance.is_dir():
        for file in sorted(conformance.glob("*.json")):
            try:
                document = json.loads(file.read_text(encoding="utf-8"))
                valid = sum(1 for vector in document["vectors"] if vector.get("valid"))
                counts[document["kind"]] = (valid, len(document["vectors"]) - valid)
            except (ValueError, KeyError, TypeError, AttributeError):
                continue
    rows = []
    for kind in kinds():
        schema = json.loads((SCHEMAS / f"{kind}.schema.json").read_text(encoding="utf-8"))
        valid, refused = counts.get(kind, (0, 0))
        rows.append({"kind": kind, "required": len(schema.get("required", [])), "accepted_vectors": valid, "refused_vectors": refused})
    return rows


def render_markdown(rows: list[dict[str, Any]], consumers: list[dict[str, Any]] | None = None, current: str | None = None) -> str:
    lines = ["# Contract matrix", "", "Generated by `armor-contract-check matrix --markdown`; do not edit by hand.", "",
             "| Kind | Required fields | Accepted vectors | Refused vectors |", "|---|---|---|---|"]
    for row in rows:
        lines.append(f"| {row['kind']} | {row['required']} | {row['accepted_vectors']} | {row['refused_vectors']} |")
    if consumers:
        lines += ["", f"Who was last checked against which version of the contracts (current: {current or 'unknown'}):", "",
                  "| Consumer | Checked against | State |", "|---|---|---|"]
        for item in consumers:
            behind = current is not None and _key(item["checked_against"]) < _key(current)
            lines.append(f"| {item['name']} | {item['checked_against']} | {'behind' if behind else 'current'} |")
    return "\n".join(lines) + "\n"


def _key(version: str) -> tuple[int, ...]:
    return tuple(int(part) for part in version.split("."))


def _checkout_root() -> Path | None:
    """The ARMOR-COMMON checkout this file lives in (None when installed as a plain package)."""
    root = Path(__file__).resolve().parents[2]
    return root if (root / "conformance").is_dir() and (root / "armor.project.json").is_file() else None


def _matrix(markdown: bool, check: str | None, with_consumers: bool) -> int:
    root = _checkout_root()
    rows = matrix_rows(root / "conformance" if root else None)
    consumers: list[dict[str, Any]] | None = None
    current: str | None = None
    if with_consumers and root and (root / "registry" / "compat.json").is_file():
        consumers = json.loads((root / "registry" / "compat.json").read_text(encoding="utf-8"))["consumers"]
        current = json.loads((root / "armor.project.json").read_text(encoding="utf-8"))["version"]
    if check is not None:
        wanted = render_markdown(rows, consumers, current)
        found = Path(check).read_text(encoding="utf-8").replace("\r\n", "\n") if Path(check).is_file() else ""
        if found != wanted:
            print(f"{check} is out of date: run armor-contract-check matrix --markdown", file=sys.stderr)
            return 1
        print("CONTRACT_MATRIX=PASS")
        return 0
    if markdown:
        sys.stdout.write(render_markdown(rows, consumers, current))
    else:
        print(json.dumps({"kinds": rows, "consumers": consumers or []}, indent=2))
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="armor-contract-check", description="Validate A.R.M.O.R. messages and vector files against the published contracts.")
    sub = parser.add_subparsers(dest="command", required=True)
    message = sub.add_parser("message", help="validate one JSON message for a topic")
    message.add_argument("topic")
    message.add_argument("file", nargs="?", help="JSON file (standard input when omitted)")
    vectors = sub.add_parser("vectors", help="run vector files against the schemas")
    vectors.add_argument("paths", nargs="+")
    matrix = sub.add_parser("matrix", help="the contracts and their vectors")
    matrix.add_argument("--markdown", action="store_true")
    matrix.add_argument("--consumers", action="store_true", help="add the version of the contracts each consumer was last checked against (not part of the checked file: the pins move on their own)")
    matrix.add_argument("--check", metavar="FILE", help="fail when FILE differs from the generated markdown")
    sub.add_parser("kinds", help="list the kinds that have a schema")
    try:
        args = parser.parse_args(argv)
    except SystemExit as error:
        return int(error.code) if isinstance(error.code, int) else 2
    if args.command == "kinds":
        print("\n".join(kinds()))
        return 0
    if args.command == "matrix":
        return _matrix(args.markdown, args.check, args.consumers)
    if args.command == "message":
        try:
            text = Path(args.file).read_text(encoding="utf-8") if args.file else sys.stdin.read()
            payload = json.loads(text)
        except (OSError, ValueError) as error:
            print(f"cannot read the message: {error}", file=sys.stderr)
            return 2
        try:
            validate_message(args.topic, payload)
        except ContractError as error:
            print(f"REFUSED: {error}", file=sys.stderr)
            return 1
        print("ACCEPTED")
        return 0
    files = collect_vector_files(args.paths)
    if not files:
        print("no vector files found", file=sys.stderr)
        return 2
    total = 0
    problems: list[str] = []
    for file in files:
        count, found = check_vector_file(file)
        total += count
        problems.extend(found)
    for line in problems:
        print(line, file=sys.stderr)
    print(f"VECTORS={'FAIL' if problems else 'PASS'} checked={total} files={len(files)}")
    return 1 if problems else 0


if __name__ == "__main__":
    raise SystemExit(main())
